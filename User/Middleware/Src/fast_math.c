// 正弦查表 + 线性插值
float qsin(float x) {
    float pos = x * Q_INV_TWO_PI;
    pos = pos - (int)pos;
    if (pos < 0.0f) pos += 1.0f;
    
    float idx_f = pos * LUT_SIN_SIZE;
    int idx = (int)idx_f;
    float frac = idx_f - (float)idx;
    
    return sin_lut[idx] + frac * (sin_lut[idx + 1] - sin_lut[idx]);
}

// 余弦基于正弦偏移
float qcos(float x) {
    return qsin(x + Q_HALF_PI);
}

// 正切
float qtan(float x) {
    float c = qcos(x);
    if (c > -1e-5f && c < 1e-5f) {
        return (c >= 0.0f) ? 100000.0f : -100000.0f;
    }
    return qsin(x) / c;
}

// 快速 atan2：专为加速度计计算 Roll/Pitch 及四元数转航向角优化
// 极大降低 CPU 周期开销，最大误差 < 0.03 度
float qatan2(float y, float x) {
    if (x == 0.0f && y == 0.0f) return 0.0f;
    
    float abs_y = (y < 0.0f) ? -y : y;
    float angle;
    
    if (x >= 0.0f) {
        float r = (x - abs_y) / (x + abs_y);
        angle = 0.785398163f - 0.785398163f * r;
    } else {
        float r = (x + abs_y) / (abs_y - x);
        angle = 2.35619449f - 0.785398163f * r;
    }
    
    return (y < 0.0f) ? -angle : angle;
}

// 快速反正切
float qatan(float x) {
    return qatan2(x, 1.0f);
}

// 快速 asin：专为四元数转 Pitch 角设计 (Pitch = asin(2*(q0*q2 - q1*q3)))
float qasin(float x) {
    if (x >= 1.0f) return Q_HALF_PI;
    if (x <= -1.0f) return -Q_HALF_PI;
    
    // 姿态解算绝大部分时间 |x| <= 0.707，采用多项式展开，零除法与无开方
    float x2 = x * x;
    return x * (1.0f + x2 * (0.16666667f + x2 * (0.075f + x2 * 0.04464286f)));
}

// 快速 acos
float qacos(float x) {
    return Q_HALF_PI - qasin(x);
}
